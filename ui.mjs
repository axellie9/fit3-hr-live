import { HeartRateProbe } from './probe.mjs';
const $=id=>document.getElementById(id);
const events=[];let lastReading=null;
function showAge(){
 if(!lastReading)return;
 const stale=Date.now()-Date.parse(lastReading.receivedAt)>15000;
 $('reading').textContent=`${stale?'DATA LAMA — ':''}${lastReading.bpm} bpm`;
 $('details').textContent=`Waktu TERIMA (bukan timestamp gelang): ${lastReading.receivedAt}; sumber ${lastReading.source}; hex ${lastReading.rawHex}; kontak ${lastReading.contact===null?'tidak diketahui':lastReading.contact?'terdeteksi':'TIDAK terdeteksi'}. Cocokkan dengan layar gelang. Ini kandidat pembacaan, belum validasi independen.`;
}
function emit(event){
 if(event.kind==='reset'){
   lastReading=null;$('reading').textContent='Belum ada data di sesi ini';$('details').textContent='Sesi lama dibersihkan. Menunggu notifikasi baru.';
   $('device').textContent='Perangkat: belum dipilih';$('status').textContent='Tidak ada sesi terverifikasi.';$('disconnect').disabled=false;
 }
 if(event.kind==='device')$('device').textContent=`Dipilih: ${event.name} (identitas bukan diverifikasi otomatis)`;
 if(event.kind==='status'||event.kind==='error')$('status').textContent=event.text;
 if(event.kind==='reading'){lastReading=event;showAge();}
 const safe=event.kind==='device'?{kind:'device',name:'REDACTED'}:event;
 events.push({loggedAt:new Date().toISOString(),...safe});if(events.length>1000)events.shift();
 $('log').textContent=events.slice(-15).map(e=>JSON.stringify(e)).join('\n');
}
const probe=new HeartRateProbe({bluetooth:navigator.bluetooth,emit});
$('environment').textContent=`Secure context: ${window.isSecureContext}; Web Bluetooth: ${!!navigator.bluetooth?.requestDevice}. Desktop/browser test bukan bukti iPhone.`;
$('connect').onclick=async()=>{
 $('connect').disabled=true;$('disconnect').disabled=false;
 try{await probe.connect();}catch(error){probe.disconnect();emit({kind:'error',text:`Belum berhasil: ${error.name}: ${error.message}. Jangan reset gelang. Service tidak ditemukan bukan bukti seluruh koneksi Fit3 mustahil.`});}
 finally{$('connect').disabled=false;}
};
$('disconnect').onclick=()=>{probe.disconnect();$('disconnect').disabled=true;};
$('export').onclick=()=>{
 const text='UNVALIDATED DEVICE LOG — may contain personal health data. No synthetic data generated by this page. Device names/IDs redacted.\n'+events.map(e=>JSON.stringify(e)).join('\n');
 const url=URL.createObjectURL(new Blob([text],{type:'text/plain'}));const a=document.createElement('a');a.href=url;a.download='fit3-hr-log.txt';a.click();setTimeout(()=>URL.revokeObjectURL(url),1000);
};
setInterval(showAge,1000);
window.addEventListener('pagehide',()=>probe.disconnect());
